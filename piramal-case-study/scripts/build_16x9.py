"""Generate variants/landscape-16x9.html (1920 × 1080) from index.html.

index.html is the single source: it carries the 16:9 layout as `#root.wide`
CSS rules plus a few `WIDE` switches in its script. This script only swaps
the canvas size and turns that mode on, so both cuts always share timing,
copy, audio and assets. Run it after any edit to index.html (and after
scripts/build_vo.py, which rewrites the time map inside index.html).

    python3 scripts/build_16x9.py
    npx hyperframes@0.8.91 render -c variants/landscape-16x9.html ...

The file lives in variants/ because a project may only have one root-level
composition (lint: multiple_root_compositions). Asset URLs stay
root-relative ("assets/..."): compositions are served with the project root
as their base URL.
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "index.html")).read()

SWAPS = [
    ('<html lang="en" data-resolution="square">', '<html lang="en" data-resolution="landscape">'),
    ('<meta name="viewport" content="width=1080, height=1080" />', '<meta name="viewport" content="width=1920, height=1080" />'),
    ("      html,\n      body {\n        width: 1080px;", "      html,\n      body {\n        width: 1920px;"),
    ('    <div\n      id="root"\n', '    <div\n      id="root"\n      class="wide"\n'),
    ('      data-width="1080"\n', '      data-width="1920"\n'),
]
out = src
for a, b in SWAPS:
    assert out.count(a) == 1, f"expected exactly one match for: {a[:60]!r}"
    out = out.replace(a, b)
out = out.replace("<title>", "<!-- generated by scripts/build_16x9.py from index.html — edit index.html, not this file -->\n    <title>", 1)
os.makedirs(os.path.join(ROOT, "variants"), exist_ok=True)
open(os.path.join(ROOT, "variants", "landscape-16x9.html"), "w").write(out)
print("wrote variants/landscape-16x9.html (1920x1080)")
