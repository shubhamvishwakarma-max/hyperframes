"""Generate variants/v1-46s-landscape-16x9.html — the 16:9 cut of v1.

v1 is the 46 s version rendered at commit 5a87914
(dt_piramal-finance_customer_video_01_v1_1080x1080.mp4): full original
narration, upbeat music, hook on screen from frame 0, KPIs 5,704+ / 1,343 /
51.6%, "Apply for Free Pilot" end frame. Its audio stems are kept under
assets/audio/v1/.

The widescreen layout is the same one the current cut uses: the `#root.wide`
CSS block is copied from today's index.html, and the v1 script gets the same
`WIDE` switches. Run from the repository checkout (it reads v1 from git):

    python3 scripts/build_v1_16x9.py
    npx hyperframes@0.8.91 render --strict -c variants/v1-46s-landscape-16x9.html ...
"""

import os
import subprocess

V1_COMMIT = "5a87914"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_PATH = os.path.basename(ROOT) + "/index.html"

src = subprocess.run(["git", "show", f"{V1_COMMIT}:{REPO_PATH}"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
current = open(os.path.join(ROOT, "index.html")).read()

# the widescreen CSS block, exactly as the current composition defines it
a = current.index("      /* ================= 16:9 layout")
b = current.index("    </style>", a)
wide_css = current[a:b] + (
    "      #root.wide #prog {\n"  # v1-only: the 51.6% progress line, centred
    "        left: 610px;\n"
    "      }\n"
)

out = src


def swap(old, new):
    global out
    assert out.count(old) == 1, f"expected exactly one match for: {old[:70]!r}"
    out = out.replace(old, new)


# layout mode
swap("    </style>\n  </head>", "\n" + wide_css + "    </style>\n  </head>")
swap('        <div id="cam" class="layer">', '        <div id="camshift" class="layer">\n        <div id="cam" class="layer">')
swap("        </div>\n\n        <!-- SCENE 3/4 overlays", "        </div>\n        </div>\n\n        <!-- SCENE 3/4 overlays")
swap(
    '        const AVC = ["#f8e3d2",',
    '        const WIDE = document.getElementById("root").classList.contains("wide");\n'
    "        const CX = WIDE ? 960 : 540;\n\n"
    '        const AVC = ["#f8e3d2",',
)
swap("        const COLS = 8,", "        const COLS = WIDE ? 13 : 8,")
swap(
    '        const grid = $("#s1-grid");',
    '        const grid = $("#s1-grid");\n'
    "        const GRID_W = COLS * (CW + GX) - 12;\n"
    '        grid.style.width = GRID_W + "px";\n'
    '        grid.style.left = -GRID_W / 2 + "px";',
)
swap("            const dx = x + CW / 2 - 890,", "            const dx = x + CW / 2 - GRID_W / 2,")
swap('tl.to("#kpi", { opacity: 0, scale: 0.96, transformOrigin: "540px 480px",', 'tl.to("#kpi", { opacity: 0, scale: 0.96, transformOrigin: CX + "px 480px",')
swap(
    '        tl.to("#s9-cmp", { opacity: 0, y: 10, duration: 0.5, ease: E.in }, 43.25);\n'
    '        tl.to("#s9-hl", { y: 232, duration: 0.9, ease: E.io }, 43.45);',
    "        if (WIDE) {\n"
    '          tl.to(["#s9-left", "#lbl-man", "#lbl-int", "#beam", "#ripple", "#node"], { opacity: 0, duration: 0.5, ease: E.in }, 43.25);\n'
    '          tl.to("#s9-right", { x: 40, duration: 0.9, ease: E.io }, 43.45);\n'
    "        } else {\n"
    '          tl.to("#s9-cmp", { opacity: 0, y: 10, duration: 0.5, ease: E.in }, 43.25);\n'
    '          tl.to("#s9-hl", { y: 232, duration: 0.9, ease: E.io }, 43.45);\n'
    "        }",
)

# 1920 × 1080 canvas, wide mode on
swap('<html lang="en" data-resolution="square">', '<html lang="en" data-resolution="landscape">')
swap('<meta name="viewport" content="width=1080, height=1080" />', '<meta name="viewport" content="width=1920, height=1080" />')
swap("      html,\n      body {\n        width: 1080px;", "      html,\n      body {\n        width: 1920px;")
swap('    <div\n      id="root"\n', '    <div\n      id="root"\n      class="wide"\n')
swap('      data-width="1080"\n', '      data-width="1920"\n')

# v1 audio stems
for name in ("voiceover", "music", "sfx"):
    swap(f'src="assets/audio/{name}.wav"', f'src="assets/audio/v1/{name}.wav"')

out = out.replace(
    "<title>",
    f"<!-- generated by scripts/build_v1_16x9.py from {V1_COMMIT}:index.html (v1, 46 s) — do not edit by hand -->\n    <title>",
    1,
)
os.makedirs(os.path.join(ROOT, "variants"), exist_ok=True)
open(os.path.join(ROOT, "variants", "v1-46s-landscape-16x9.html"), "w").write(out)
print("wrote variants/v1-46s-landscape-16x9.html (1920x1080, 46 s)")
